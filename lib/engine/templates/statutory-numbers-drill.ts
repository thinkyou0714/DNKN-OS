type Params = {
  case_index: number;
};

export const statutoryNumbersDrill = defineTemplate<Params>({
  topic: "法令数値の横断ドリル",
  subject: "法規",
  exam: "denken3",
  difficulty: 2,
  pastExam: {
    area: "電気事業法・電気工作物",
    frequency: "high",
    years: [2009, 2013, 2016, 2019, 2022, 2024],
  },
  paramSpecs: { case_index: { realistic_range: [0, CASES.length - 1] } },
  paramOrder: ["case_index"],
  draw(rng) {
    return { case_index: Math.floor(rng() * CASES.length) };
  },
  buildFrom({ case_index: caseIndex }) {
    const c = CASES[caseIndex];
    if (!c) return null;
    const answerText = formatClean(c.answer);
    const choices = c.pool.map((v) => formatClean(v));
    const distractors = c.pool
      .filter((v) => v !== c.answer)
      .map((v) => ({
        text: formatClean(v),
        reason: c.reasons[v] ?? "類似する他の法令数値との取り違え",
      }));
    return {
      format: "multiple_choice" as const,
      params: { case_index: { value: caseIndex, realistic_range: [0, CASES.length - 1] as [number, number] } },
      answerValue: c.answer,
      answerUnit: c.unit,
      answerText,
      choices,
      distractors,
      facts: { caseIndex, answer: c.answer },
      defaultStatement: `電気事業法および関係法令について、${c.question}は?`,
      defaultSolution: [c.fact, `=${answerText}${c.unit}`],
      physicallyValid: true,
    };
  },
});
