/** どの空欄を誤らせるかのパターン（4つの誤答分）。 */
const CORRUPT_PATTERNS: ReadonlyArray<ReadonlyArray<readonly number[]>> = [
  [[0], [1], [2], [0, 1]],
  [[1], [2], [0, 2], [1, 2]],
  [[2], [0], [1, 2], [0, 1]],
  [[0, 1], [1, 2], [0, 2], [0]],
];

const LABELS = ["ア", "イ", "ウ"] as const;

type Params = {
  case_index: number;
  pattern: number;
};

/** 空欄の値の組から選択肢テキストを作る。 */
function renderChoice(values: readonly string[]): string {
  return values.map((v, i) => `(${LABELS[i]}) ${v}`).join("　");
}

export const statuteBlankFill = defineTemplate<Params>({
  topic: "法令条文の空欄補充",
  subject: "法規",
  exam: "denken3",
  difficulty: 2,
  pastExam: {
    area: "電気事業法・電気工作物",
    frequency: "high",
    years: [2008, 2011, 2014, 2017, 2020, 2023, 2025],
  },
  paramSpecs: {
    case_index: { realistic_range: [0, CASES.length - 1] },
    pattern: { realistic_range: [0, CORRUPT_PATTERNS.length - 1] },
  },
  paramOrder: ["case_index", "pattern"],
  draw(rng) {
    return {
      case_index: Math.floor(rng() * CASES.length),
      pattern: Math.floor(rng() * CORRUPT_PATTERNS.length),
    };
  },
  buildFrom({ case_index: caseIndex, pattern }) {
    const c = CASES[caseIndex];
    const pat = CORRUPT_PATTERNS[pattern];
    if (!c || !pat) return null;

    const correct = c.blanks.map((b) => b.correct);
    const answerText = renderChoice(correct);

    const distractors: { text: string; reason: string }[] = [];
    for (let i = 0; i < pat.length; i++) {
      const corruptIdx = pat[i] as readonly number[];
      const values = [...correct];
      const changed: string[] = [];
      for (const bi of corruptIdx) {
        const blank = c.blanks[bi];
        if (!blank) return null;
        const wrong = blank.wrongs[(pattern + i) % blank.wrongs.length];
        if (wrong === undefined) return null;
        values[bi] = wrong;
        changed.push(`(${LABELS[bi]})は「${blank.correct}」が正しい`);
      }
      distractors.push({ text: renderChoice(values), reason: changed.join("、") });
    }

    // 選択肢が相互に一意でなければ成立しない。
    const texts = new Set([answerText, ...distractors.map((d) => d.text)]);
    if (texts.size !== 5) return null;

    // 本試の並び順に近づけるため、正解の位置は決定論的に散らす。
    const ordered = [...distractors.map((d) => d.text)];
    const insertAt = (caseIndex + pattern) % 5;
    ordered.splice(insertAt, 0, answerText);

    const body = c.body.replace(/\{(\d)\}/g, (_m, d: string) => `(${LABELS[Number(d)]})`);

    return {
      params: {
        case_index: { value: caseIndex, realistic_range: [0, CASES.length - 1] as [number, number] },
        pattern: { value: pattern, realistic_range: [0, CORRUPT_PATTERNS.length - 1] as [number, number] },
      },
      answerValue: insertAt + 1,
      answerUnit: "",
      answerText,
      choices: ordered,
      distractors,
      likelyWrongChoice: distractors[0]?.text ?? answerText,
      facts: { caseIndex, pattern },
      defaultStatement:
        `次の文章は、${c.source}に関する記述である。\n${body}\n` +
        "上記の記述中の(ア)〜(ウ)に当てはまる語句または数値として、正しい組合せを選べ。",
      defaultSolution: [c.note, `正しい組合せ: ${answerText}`],
      physicallyValid: true,
    };
  },
});
